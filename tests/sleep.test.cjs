const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const script = fs.readFileSync('src/sleep.js', 'utf8');
function page({ fields = [], media = [], frames = [], devices } = {}) {
  const listeners = {};
  const window = { frames, addEventListener(type, listener) { listeners[type] = listener; } };
  const document = { readyState: 'complete', querySelectorAll: selector => selector === 'audio,video' ? media : fields };
  vm.runInNewContext(script, { window, document, navigator: { mediaDevices: devices } });
  return { safe: window.__felarisCanSleep, window, document, listeners };
}
assert.equal(page().safe(), true);
assert.equal(page({ frames: [{}] }).safe(), false);
assert.equal(page({ fields: [{ value: 'draft', defaultValue: '' }] }).safe(), false);
assert.equal(page({ fields: [{ type: 'checkbox', checked: true, defaultChecked: false }] }).safe(), false);
assert.equal(page({ fields: [{ options: [{ selected: true, defaultSelected: false }] }] }).safe(), false);
assert.equal(page({ media: [{ paused: false, ended: false }] }).safe(), false);
assert.equal(page({ media: [{ paused: true, ended: false }] }).safe(), true);
const autoPaused = page();
const media = {};
autoPaused.listeners.play({ target: media });
autoPaused.document.hidden = true;
autoPaused.listeners.pause({ target: media });
assert.equal(autoPaused.safe(), false, 'hiding a tab must not discard auto-paused playback');
autoPaused.document.hidden = false;
autoPaused.listeners.pause({ target: media });
assert.equal(autoPaused.safe(), true, 'an explicit visible pause releases playback protection');
const edited = page();
edited.listeners.input();
assert.equal(edited.safe(), false, 'input keeps contenteditable and custom editors awake');
const unloading = page();
unloading.window.addEventListener('beforeunload', () => {});
assert.equal(unloading.safe(), false);
const loading = page();
loading.document.readyState = 'loading';
assert.equal(loading.safe(), false);
(async () => {
  let finish;
  const devices = { getUserMedia: () => new Promise(resolve => { finish = resolve; }) };
  const capture = page({ devices });
  const pending = devices.getUserMedia();
  assert.equal(capture.safe(), false, 'pending capture requests stay awake');
  let ended;
  finish({ getTracks: () => [{ addEventListener: (_, listener) => { ended = listener; } }] });
  await pending;
  assert.equal(capture.safe(), false, 'live captures stay awake');
  ended();
  assert.equal(capture.safe(), true);
  console.log('Automatic sleep guards passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
